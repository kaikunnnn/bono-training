/** p1（オーナー案のセクション名）をもとに、各回のタイトルにカードと同じ「見る／やってみる」を付ける */
export function makeP4(p1: Direction): Direction {
  const kindOf = new Map(EDIT_CARDS.map((c) => [c.number, c.kind]));
  const rows = p1.rows ?? [];
  return {
    ...p1,
    label: "3 編集で補う",
    promise:
      "撮り直しなし。各動画の頭に「見る回／やってみる回」のカードを入れ、頼み方の文は動画の言葉から起こして記事に置く。ページは1（分かれ目）の言葉＋各回の印＋頼み方",
    sectionGoals: [
      "",
      "やってみる → 見る → やってみる → やってみる。残るもの：業種のレポートと、足りないもののメモ",
      "見る → やってみる ×3。残るもの：仕様・挙動と部品のレポート、触った参考アプリのメモ",
      "実演を2つ見る → 自分で作り直す",
    ],
    articleTitles: p1.articleTitles.map((title, index) => {
      const kind = kindOf.get(rows[index]?.number ?? "");
      return kind ? `${title}（${kind}）` : title;
    }),
    content: {
      ...p1.content,
      overview: {
        ...p1.content.overview,
        paragraphs: [
          ...p1.content.overview.paragraphs,
          "各回のはじめに「見る回」か「やってみる回」かが出ます。やってみる回では、記事にある頼み方の文をコピーして、自分のAI（Claude・ChatGPT・Geminiのどれでも）で同じことをします。",
        ],
      },
    },
  };
}
