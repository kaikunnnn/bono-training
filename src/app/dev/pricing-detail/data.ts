/** E1: 要約2カラム（既定） / E2: フィードバック主役・変化ストーリー */
export type EPattern = "E1" | "E2";

export const E_PATTERNS: EPattern[] = ["E1", "E2"];

/** 既定パターン（E1＝要約2カラム） */
export const DEFAULTS = {
  p: "E1" as EPattern,
};

/** クエリ値のホワイトリスト検証（不正値は既定へフォールバック） */
export function parseEPattern(v: string | null): EPattern {
  return E_PATTERNS.includes(v as EPattern) ? (v as EPattern) : DEFAULTS.p;
}

